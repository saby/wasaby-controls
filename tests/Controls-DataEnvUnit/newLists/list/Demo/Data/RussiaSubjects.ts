export const AllSubjects = unflatten(flatSubjects);
export { getSomeSubjects };

function unflatten(flatItems: (TFlatItem | string)[], parentId: TParentKey = null): TItem[] {
    const items: TItem[] = [];
    let idCounter: number = 0;

    for (const item of flatItems) {
        const key = parentId === null ? `${++idCounter}` : `${parentId}_${++idCounter}`;
        if (typeof item === 'string') {
            items.push({
                [KEY_PROPERTY]: key,
                [DISPLAY_PROPERTY]: item,
                [PARENT_PROPERTY]: parentId,
                [NODE_PROPERTY]: null,
            });
        } else {
            const newItem: TItem = {
                [KEY_PROPERTY]: key,
                [DISPLAY_PROPERTY]: item[DISPLAY_PROPERTY],
                [PARENT_PROPERTY]: parentId,
                [NODE_PROPERTY]:
                    Array.isArray(item.children) && item.children.length > 0 ? true : null,
            };
            items.push(newItem);

            if (newItem[NODE_PROPERTY]) {
                items.push(...unflatten(item.children, newItem[KEY_PROPERTY]));
            }
        }
    }
    return items;
}

function getRootItems(): TItem[] {
    return AllSubjects.filter(({ parent }) => parent === null);
}

function getSortedRootItems(
    description: number | number[] | [key: TKey, count: number][]
): TItem[] {
    const rootItems = getRootItems();

    if (description instanceof Array && description[0] instanceof Array) {
        return (description as [key: TKey, count: number][]).reduce((acc, [key]) => {
            const item = rootItems.find((i) => i[KEY_PROPERTY] === key);
            if (item) {
                acc.push(item);
            }
            return acc;
        }, [] as TItem[]);
    } else {
        const rootLength = Math.min(
            typeof description === 'number' ? description : description.length,
            rootItems.length
        );
        return rootItems.slice(0, rootLength);
    }
}

function getChildCountMap(
    rootKeys: TKey[],
    countOrDescription: number | number[] | [key: TKey, count: number][]
): Map<
    TParentKey,
    {
        current: number;
        max: number;
    }
> {
    if (typeof countOrDescription === 'number') {
        return new Map();
    }

    if (countOrDescription[0] instanceof Array) {
        return new Map(
            rootKeys.map((rootKey) => {
                const meta = (countOrDescription as [key: TKey, count: number][]).find(
                    ([key]) => key === rootKey
                );

                return [
                    rootKey,
                    {
                        current: 0,
                        max: meta ? meta[1] : 0,
                    },
                ];
            })
        );
    } else {
        return new Map(
            rootKeys.map((rootKey, index) => [
                rootKey,
                {
                    current: 0,
                    max: (countOrDescription as number[])[index],
                },
            ])
        );
    }
}

function getSomeSubjects(
    countOrDescription: number | number[] | [key: TKey, count: number][]
): TItem[] {
    const sortedRootItems = getSortedRootItems(countOrDescription);
    const sortedRootKeys = sortedRootItems.map((i) => i[KEY_PROPERTY]);

    const isFromSortedRoot = (i: TItem): boolean => {
        if (sortedRootKeys.indexOf(i[KEY_PROPERTY]) !== -1) {
            return true;
        } else {
            const parentItem =
                i[PARENT_PROPERTY] !== null &&
                AllSubjects.find((parent) => parent[KEY_PROPERTY] === i[PARENT_PROPERTY]);
            return !!(parentItem && isFromSortedRoot(parentItem));
        }
    };

    const childCountMap = getChildCountMap(sortedRootKeys, countOrDescription);

    const isInLimit = ({ parent }: TItem) => {
        const meta = childCountMap.get(parent);
        if (!meta) {
            return true;
        }

        const { current, max } = meta;

        if (current < max) {
            meta.current++;
            return true;
        } else {
            return false;
        }
    };

    return AllSubjects.filter((item) => isFromSortedRoot(item) && isInLimit(item));
}
